"""Builds src/js/temporal_js.h from the JavaScript in src/js/temporal/*.js (concatenated in file-name order).

MSVC caps one string literal at about 16 KB and a concatenated one at 64 KB, so the source becomes an array of
raw-string pieces that prelude.cpp joins. Run after changing any file in src/js/temporal:
    python tools/gen_temporal.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = sorted((ROOT / 'src' / 'js' / 'temporal').glob('*.js'))
OUT = ROOT / 'src' / 'js' / 'temporal_js.h'
PIECE = 15000  # bytes per raw string, under MSVC's 16380

def main():
    pieces, current = [], ''
    for path in SOURCES:
        for line in path.read_text(encoding='utf-8').splitlines(keepends=True):
            if ')JS"' in line:
                raise SystemExit(f'{path.name}: a line holds the raw string terminator )JS"')
            if len(current.encode('utf-8')) + len(line.encode('utf-8')) > PIECE:
                pieces.append(current)
                current = ''
            current += line
    pieces.append(current)
    out = ['// Generated by tools/gen_temporal.py from src/js/temporal/*.js. Do not edit; change those files instead.',
           '#pragma once', '', 'namespace tb::js {', '', 'static const char* const kTemporalJsParts[] = {']
    out += ['R"JS(' + p + ')JS",' for p in pieces]
    out += ['};', '', '}  // namespace tb::js', '']
    OUT.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {len(pieces)} pieces from {len(SOURCES)} files')

main()
