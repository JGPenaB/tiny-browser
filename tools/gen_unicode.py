"""Builds src/js/unicode_data.h, the Unicode property tables used by RegExp property escapes and identifiers.

The data is read from the property-escape tests of test262 (third_party/test262), which list the exact code
points of every property and every name it can be written with:
    python tools/gen_unicode.py
"""
import os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "third_party", "test262", "test", "built-ins", "RegExp", "property-escapes", "generated")


def parse(path):
    text = open(path, encoding="utf-8").read()
    version = re.search(r"Unicode v([\d.]+)", text).group(1)
    body = re.search(r"const matchSymbols = buildString\(\{(.*?)\}\);", text, re.S).group(1)
    lone = re.search(r"loneCodePoints: \[(.*?)\]", body, re.S).group(1)
    rng = re.search(r"ranges: \[(.*)\]", body, re.S).group(1)
    ranges = [(int(x, 16), int(x, 16)) for x in re.findall(r"0x[0-9A-Fa-f]+", lone)]
    ranges += [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\[(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\]", rng)]
    ranges.sort()
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    names = sorted(set(re.findall(r"\\p\{([^}]+)\}", text)))
    return version, merged, names


def main():
    props, version = [], ""
    for f in sorted(os.listdir(src)):
        if not f.endswith(".js"):
            continue
        version, ranges, names = parse(os.path.join(src, f))
        props.append((f[:-3], ranges, names))
    out = ["// Unicode %s property tables. Generated by tools/gen_unicode.py from the test262 property-escape tests;" % version,
           "// do not edit by hand.", "#pragma once", "#include <cstdint>", "", "namespace tb::js {", ""]
    total = 0
    for i, (name, ranges, names) in enumerate(props):
        flat = ",".join("%d,%d" % r for r in ranges)
        total += len(ranges)
        out.append("// %s" % name)
        out.append("static const uint32_t kUni%d[] = {%s};" % (i, flat if flat else "0"))
    out.append("")
    out.append("struct UniTable {\n    const uint32_t* ranges;  // lo, hi pairs in ascending order\n    uint32_t count;          // number of pairs\n};")
    out.append("static const UniTable kUniTables[] = {")
    for i, (name, ranges, names) in enumerate(props):
        out.append("    {kUni%d, %d}," % (i, len(ranges)))
    out.append("};")
    out.append("")
    out.append("// Every way a property can be written in a property escape, sorted by name, with the table it selects.")
    out.append("struct UniName {\n    const char* name;\n    uint16_t table;\n};")
    entries = sorted((n, i) for i, (_, _, names) in enumerate(props) for n in names)
    out.append("static const UniName kUniNames[] = {")
    for n, i in entries:
        out.append('    {"%s", %d},' % (n, i))
    out.append("};")
    idx = {name: i for i, (name, _, _) in enumerate(props)}
    out.append("")
    out.append("enum { kUniIdStart = %d, kUniIdContinue = %d };" % (idx["ID_Start"], idx["ID_Continue"]))
    out.append("")
    out.append("}  // namespace tb::js")
    path = os.path.join(root, "src", "js", "unicode_data.h")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("Unicode %s: %d properties, %d names, %d ranges, %d KB of source" % (version, len(props), len(entries), total, os.path.getsize(path) // 1024))


if __name__ == "__main__":
    main()
