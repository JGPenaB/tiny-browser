"""Builds src/js/emoji_data.h: the emoji sequences behind the properties of strings that a regular expression
with the v flag can name (ECMA-262 table 68: Basic_Emoji, RGI_Emoji_ZWJ_Sequence and the rest).

The data comes from two Unicode files (UTS #51), which are not kept in the repository. Download
emoji-sequences.txt and emoji-zwj-sequences.txt from https://www.unicode.org/Public/<version>/emoji/ into
third_party/unicode-emoji (or name another folder on the command line), then:
    python -I tools/gen_emoji.py [folder]
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
folder = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "third_party", "unicode-emoji")
# the order RGI_Emoji lists them in; every name here is a property of its own
NAMES = ["Basic_Emoji", "Emoji_Keycap_Sequence", "RGI_Emoji_Modifier_Sequence", "RGI_Emoji_Flag_Sequence", "RGI_Emoji_Tag_Sequence",
         "RGI_Emoji_ZWJ_Sequence"]


def read(name, singles, seqs):
    """Adds the file's entries to singles[property] (code points) and seqs[property] (lists of code points)."""
    version = ""
    for line in open(os.path.join(folder, name), encoding="utf-8"):
        m = re.match(r"# Version: ([\d.]+)", line)
        if m:
            version = m.group(1)
        fields = [f.strip() for f in line.split("#")[0].split(";")]
        if len(fields) < 2 or not fields[0]:
            continue
        points, prop = fields[0], fields[1]
        if prop not in NAMES:
            sys.exit("%s: unknown property %s" % (name, prop))
        if ".." in points:
            lo, hi = (int(x, 16) for x in points.split(".."))
            singles[prop].extend(range(lo, hi + 1))
        else:
            cps = [int(x, 16) for x in points.split()]
            if len(cps) == 1:
                singles[prop].append(cps[0])
            else:
                seqs[prop].append(cps)
    return version


def ranges(points):
    out = []
    for cp in sorted(set(points)):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def main():
    singles, seqs = {n: [] for n in NAMES}, {n: [] for n in NAMES}
    version = read("emoji-sequences.txt", singles, seqs)
    if read("emoji-zwj-sequences.txt", singles, seqs) != version:
        sys.exit("the two files are of different Unicode versions")
    out = ["// Unicode %s emoji sequences (UTS #51): the members of the properties of strings a regular expression with the" % version,
           "// v flag can name (ECMA-262 table 68). RGI_Emoji is all of them together. Generated by tools/gen_emoji.py from",
           "// emoji-sequences.txt and emoji-zwj-sequences.txt; do not edit by hand.",
           "#pragma once", "#include <cstdint>", "", "namespace tb::js {", ""]
    rows = []
    for i, name in enumerate(NAMES):
        r = ranges(singles[name])
        flat = [x for pair in r for x in pair]
        words = [x for s in seqs[name] for x in s + [0]]
        out.append("// %s: %d single code points, %d sequences" % (name, len(set(singles[name])), len(seqs[name])))
        out.append("static const uint32_t kEmojiRanges%d[] = {%s};" % (i, ",".join("0x%X" % x for x in flat) or "0"))
        out.append("static const uint32_t kEmojiSeqs%d[] = {%s};" % (i, ",".join("0x%X" % x for x in words) or "0"))
        rows.append('    {"%s", kEmojiRanges%d, %d, kEmojiSeqs%d, %d},' % (name, i, len(flat), i, len(words)))
    out += ["",
            "struct EmojiProperty {",
            "    const char* name;",
            "    const uint32_t* ranges;  // its single code points: lo, hi pairs in ascending order",
            "    uint32_t rangeWords;",
            "    const uint32_t* seqs;    // its sequences of several code points, one after another, each ended by 0",
            "    uint32_t seqWords;",
            "};",
            "static const EmojiProperty kEmojiProperties[] = {"] + rows + ["};", "", "}  // namespace tb::js"]
    path = os.path.join(root, "src", "js", "emoji_data.h")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("Unicode %s: %s; %d KB of source" % (version, ", ".join("%s %d+%d" % (n, len(set(singles[n])), len(seqs[n])) for n in NAMES),
                                               os.path.getsize(path) // 1024))


if __name__ == "__main__":
    main()
