"""Builds src/js/special_casing.h: the uppercase mappings of SpecialCasing.txt that turn one character into
several, taken from the list in test262's String.prototype.toUpperCase/special_casing.js.

    python tools/gen_casing.py
"""
import os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "third_party", "test262", "test", "built-ins", "String", "prototype", "toUpperCase", "special_casing.js")
text = open(src, encoding="utf-8").read()

pairs = []
for m in re.finditer(r'assert\.sameValue\("((?:\\u[0-9A-Fa-f]{4})+)"\.toUpperCase\(\),\s*"((?:\\u[0-9A-Fa-f]{4})+)"', text):
    frm = [int(x, 16) for x in re.findall(r"\\u([0-9A-Fa-f]{4})", m.group(1))]
    to = [int(x, 16) for x in re.findall(r"\\u([0-9A-Fa-f]{4})", m.group(2))]
    if len(frm) == 1 and frm != to:
        pairs.append((frm[0], to))
pairs.sort()

out = ["// Generated by tools/gen_casing.py from test262's special_casing.js: characters whose uppercase form is longer",
       "// than one code unit (SpecialCasing.txt, the unconditional mappings). Sorted by character.",
       "#pragma once",
       "",
       "namespace tb::js {",
       "",
       "struct UpperSpecial {",
       "    char16_t from;",
       "    char16_t to[4];  // zero-terminated when shorter than three units",
       "};",
       "static const UpperSpecial kUpperSpecial[] = {"]
for frm, to in pairs:
    assert len(to) <= 3
    out.append("    {0x%04X, {%s}}," % (frm, ", ".join("0x%04X" % c for c in to + [0])))
out += ["};", "", "}  // namespace tb::js", ""]
with open(os.path.join(root, "src", "js", "special_casing.h"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out))
print(len(pairs), "mappings")
