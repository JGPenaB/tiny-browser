"""Builds the headers that hold the engine's built-ins written in JavaScript:
    src/js/temporal_js.h  from src/js/temporal/*.js  (kTemporalJsParts)
    src/js/intl_js.h      from src/js/intl/*.js      (kIntlJsParts)
Each bundle is its files in name order, with src/js/shared/*.js placed after its first file (which defines the
helpers the shared code uses). MSVC caps one string literal at about 16 KB and a concatenated one at 64 KB, so the
source becomes an array of raw-string pieces that prelude.cpp joins. Run after changing any of those files:
    python tools/gen_js_parts.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
JS = ROOT / 'src' / 'js'
BUNDLES = [('temporal', 'kTemporalJsParts'), ('intl', 'kIntlJsParts')]
PIECE = 15000  # bytes per raw string, under MSVC's 16380

def build(name, symbol):
    own = sorted((JS / name).glob('*.js'))
    files = own[:1] + sorted((JS / 'shared').glob('*.js')) + own[1:]
    pieces, current = [], ''
    for path in files:
        for line in path.read_text(encoding='utf-8').splitlines(keepends=True):
            if ')JS"' in line:
                raise SystemExit(f'{path.name}: a line holds the raw string terminator )JS"')
            if len(current.encode('utf-8')) + len(line.encode('utf-8')) > PIECE:
                pieces.append(current)
                current = ''
            current += line
    pieces.append(current)
    out = [f'// Generated by tools/gen_js_parts.py from src/js/{name}/*.js and src/js/shared/*.js. Do not edit.',
           '#pragma once', '', 'namespace tb::js {', '', f'static const char* const {symbol}[] = {{']
    out += ['R"JS(' + p + ')JS",' for p in pieces]
    out += ['};', '', '}  // namespace tb::js', '']
    target = JS / f'{name}_js.h'
    target.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{target.relative_to(ROOT)}: {len(pieces)} pieces from {len(files)} files')

for name, symbol in BUNDLES:
    build(name, symbol)
